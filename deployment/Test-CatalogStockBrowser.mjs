import {createRequire} from 'node:module';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const {chromium}=createRequire(process.env.PLAYWRIGHT_MODULE+'/package.json')('playwright');
const bytes=readFileSync('.local/isolated-login-fixture.json');
const fixture=JSON.parse(bytes.toString(bytes[0]===255?'utf16le':'utf8').replace(/^\uFEFF/,''));
mkdirSync('.local/catalog-stock-browser',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});page.setDefaultTimeout(60000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const responses=[],reads=[];
 page.on('response',response=>{if(response.url().includes('/inventory/api/v1/inventories?'))reads.push(response.json().then(data=>responses.push({url:response.url(),status:response.status(),data})).catch(()=>{}));});
 await page.goto('http://127.0.0.1:5184/login',{waitUntil:'domcontentloaded'});
 await page.getByRole('textbox',{name:/^Email/}).fill(fixture.email);await page.locator('input[type=password]').fill('LocalQaOnly9');
 await page.getByRole('button',{name:'Login',exact:true}).click();await page.waitForURL('**/home');
 await page.locator('.product-card').first().waitFor();
 await page.waitForFunction(()=>[...document.querySelectorAll('.product-card .add-btn')].some(button=>button.disabled&&button.textContent.trim()!=='Checking'));
 const states=await page.locator('.product-card').evaluateAll(cards=>cards.map(card=>({title:card.querySelector('.product-title')?.textContent,store:card.querySelector('.product-store-line')?.textContent,label:card.querySelector('.add-btn')?.textContent,disabled:card.querySelector('.add-btn')?.disabled})));
 await Promise.all(reads);writeFileSync('.local/catalog-stock-browser/responses.json',JSON.stringify(responses,null,2));
 assert.ok(responses.length>0);assert.ok(responses.every(response=>[200,404].includes(response.status)),'Stock lookups must return stock or genuine absence, not API errors');
 assert.ok(states.some(state=>state.disabled&&state.label.trim()!=='Checking'));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'.local/catalog-stock-browser/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'.local/catalog-stock-browser/mobile.png',fullPage:true});assert.deepEqual(errors,[]);
 writeFileSync('.local/catalog-stock-browser/states.json',JSON.stringify(states,null,2));
 console.log('PASS real customer catalog stock controls: unavailable offers disabled; desktop/mobile no overflow or page errors; no cart/order writes');
}finally{await browser.close();}
